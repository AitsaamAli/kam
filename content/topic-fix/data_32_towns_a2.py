ntn("arifwala", """## Fertiliser, Seed and Pesticide Dealers

Arifwala's input dealers buy from national distributors that supply only registered dealers and deduct tax on each supply. Without an NTN, a dealer either cannot buy directly or suffers higher deductions. Dealers who sell to farmers on credit until harvest also benefit from a business bank account in the shop's name, which requires the NTN.

## Ginners Before the Picking Season

A ginning unit needs its NTN before it can apply for sales tax registration, and spinning mills will not buy lint without both. Because cotton picking begins in late summer, ginners should complete registration in spring; sales tax registration involves verification of the factory and its electricity connection, which takes time.

## Arhtis and Government Procurement

Commission agents in the grain market who sell wheat to flour mills or to procurement centres are paid through banks, and buyers deduct tax at rates that depend on filer status. Registering and filing reduces those deductions.

## Families Planning Purchases

Farmers whose only income is agricultural are not required to register, but a family planning to buy a tractor, car or plot benefits from filer status, because advance tax at registration is lower for persons on the Active Taxpayers List.

## Address for Rural Units

Ginning units outside the town should use the chak or mauza and the road as shown on the electricity bill. The online steps are in our [FBR registration guide](/blogs/fbr-registration-step-by-step).""")

